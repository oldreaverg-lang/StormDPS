def test_parse_nolo_areas_and_impact():
    t = lr.advisory_text(NOLO_23A)
    assert lr.issuing_center(t) == "CPHC"                  # not the backup NHC byline
    assert lr.advisory_label(t) == "Advisory 23A"
    p = lr.parse_rainfall(t)
    assert [(a["area"], a["lo_in"], a["hi_in"], a["max_in"]) for a in p["areas"]] == [
        ("eastern and southern portions of the Big Island", 8, 12, 16),
        ("western portions of the Big Island", 1, 3, 6),
        ("eastern Maui", 4, 6, 8),
        ("remainder of the Hawaiian Islands", 1, 2, 2),
    ]
    assert p["impact"].startswith("This rainfall could produce significant, life-threatening flooding")
    assert "STORM SURGE" not in lr.rainfall_section(t)     # section stops at the next hazard


def test_parse_polo_ignores_mm_and_finds_trailing_area():
    p = lr.parse_rainfall(lr.advisory_text(POLO_23))
    assert p["areas"] == [{"area": "portions of Baja California Sur",
                           "lo_in": 4.0, "hi_in": 8.0, "max_in": 10.0}]


def test_no_rainfall_section_means_no_bar():
    t = lr.advisory_text(NO_RAIN)
    res = lr.build({"center": "NHC", "label": "Advisory 9", "issued_utc": None,
                    **lr.parse_rainfall(t)}, [], None)
    assert res["available"] and not res["show"] and res["source"] == "advisory"


def test_build_advisory_bar_text():
    t = lr.advisory_text(NOLO_23A)
    adv = {"center": "CPHC", "label": "Advisory 23A", "issued_utc": "2026-09-26T12:00:00Z",
           **lr.parse_rainfall(t)}
    pts = [{"name": "Hilo, HI", "lat": 19.72, "lon": -155.08, "dist_km": 250, "total_in": 5.39},
           {"name": "Naalehu, HI", "lat": 19.06, "lon": -155.59, "dist_km": 180, "total_in": 6.05}]
    res = lr.build(adv, pts, "nws")
    assert res["show"] and res["level"] == "EXTREME" and res["max_in"] == 16
    assert res["score_text"] == "Rain up to 16 in —"
    assert res["text"].startswith(
        "Extreme rain forecast: eastern and southern portions of the Big Island 8–12 in (locally 16 in); "
        "eastern Maui 4–6 in (locally 8 in); western portions of the Big Island 1–3 in (locally 6 in).")
    assert "remainder of the Hawaiian Islands" not in res["text"]     # < 3 in areas dropped
    assert "NWS forecast, next 3 days: Naalehu, HI 6 in, Hilo, HI 5.4 in." in res["text"]
    assert res["text"].endswith("— CPHC Advisory 23A")


def test_directive_sentences_never_become_the_impact_line():
    t = ("RAINFALL: Rainfall totals of 10 to 15 inches are expected across Puerto Rico. "
         "Residents should follow the advice of local officials regarding flooding.\n\nSURF: x")
    p = lr.parse_rainfall(t)
    assert p["impact"] is None and p["areas"][0]["area"] == "Puerto Rico"


