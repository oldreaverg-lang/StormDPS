def test_model_points_bar_carries_attribution_and_caveat():
    pts = [{"name": "Hualien", "lat": 24.0, "lon": 121.6, "dist_km": 90, "total_in": 7.24},
           {"name": "Yilan", "lat": 24.75, "lon": 121.75, "dist_km": 120, "total_in": 5.1},
           {"name": "Taipei", "lat": 25.03, "lon": 121.56, "dist_km": 160, "total_in": 0.4}]
    res = lr.build(None, pts, "model")
    assert res["show"] and res["level"] == "ELEVATED" and res["source"] == "model"
    assert "up to 7.2 in at Hualien, 5.1 in at Yilan over the next 3 days" in res["text"]
    assert "Open-Meteo.com (CC BY 4.0)" in res["text"] and lr.MODEL_CAVEAT in res["text"]
    quiet = lr.build(None, [{"name": "Naha", "lat": 26.2, "lon": 127.7, "dist_km": 50, "total_in": 1.0}], "model")
    assert quiet["available"] and not quiet["show"]


def test_select_places_radius_order_and_antimeridian():
    track = [{"hour": 0, "lat": -17.0, "lon": 179.0}, {"hour": 24, "lat": -18.0, "lon": -178.0}]
    places = [(-17.8, 178.4, "Suva"), (-18.1, -178.3, "Lau Group"),
              (-13.8, -171.8, "Apia"), (-17.8, 178.4, "Suva")]
    hits = lr.select_places(track, places, radius_km=400)
    names = [h["name"] for h in hits]
    assert names == sorted(names, key=lambda n: {h["name"]: h["dist_km"] for h in hits}[n])
    assert set(names) == {"Suva", "Lau Group"}                # Apia too far, Suva once
    beyond = [{"hour": 0, "lat": 17, "lon": -155.3}, {"hour": 96, "lat": 30, "lon": -150}]
    assert lr.select_places(beyond, [(29.0, -150.5, "far")], horizon_h=72) == []


def test_sum_nws_qpf_prorates_edges():
    now = datetime(2026, 9, 26, 3, 0, tzinfo=timezone.utc)
    vals = [{"validTime": "2026-09-26T00:00:00+00:00/PT6H", "value": 25.4},   # half inside
            {"validTime": "2026-09-26T06:00:00+00:00/PT6H", "value": 50.8},
            {"validTime": "2026-09-29T00:00:00+00:00/PT6H", "value": 25.4},   # half inside (ends +75 h)
            {"validTime": "2026-09-29T06:00:00+00:00/P1D", "value": 999},     # beyond
            {"validTime": "2026-09-26T12:00:00+00:00/PT6H", "value": None}]
    assert lr.sum_nws_qpf(vals, now) == 3.0
    assert lr.sum_nws_qpf([], now) is None


def test_sum_hourly_window():
    now = datetime(2026, 9, 26, 5, 40, tzinfo=timezone.utc)
    times = [f"2026-09-26T{h:02d}:00" for h in range(4, 8)]
    assert lr.sum_hourly(times, [25.4, 25.4, 25.4, None], now) == 2.0          # 05:00 and 06:00


